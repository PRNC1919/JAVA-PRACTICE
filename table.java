class Main {
        public static void main(String[] args) {
            
            int num = 5;

            for(int i = 1, j = 10; i <= 10; i++, j--) {

                    System.out.println(num + " * " + i + " = " + num*i + " \t" + num + " * " + j + " = " + num*j);
            }
        }
    }